// Command adaptergen writes adapters/aws-generated.yaml from the service
// models bundled with the installed AWS CLI v2 (D-012, spike S4).
//
// Only operations whose first word is on a reviewed list get a label; the
// rest are left out, so the generic layer handles them and they ask.
//
//	go run ./tools/adaptergen -models <botocore/data dir> -out adapters/aws-generated.yaml
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// Reviewed verb rules. Reads are only the verbs that never change state.
var verbs = map[string]string{
	"Describe": "read", "List": "read", "Get": "read", "Head": "read", "Search": "read", "Lookup": "read",
	"Query": "read", "Scan": "read", "Select": "read",
	"Create": "create", "Put": "create", "Add": "create", "Register": "create", "Import": "create", "Copy": "create",
	"Upload": "create", "Allocate": "create", "Run": "create", "Start": "create", "Request": "create", "Issue": "create",
	"Generate": "create", "Invoke": "create", "Execute": "create", "Subscribe": "create", "Tag": "change",
	"Deploy": "create", "Provision": "create", "Submit": "create", "Publish": "send", "Send": "send",
	"Update": "change", "Modify": "change", "Set": "change", "Change": "change", "Replace": "change", "Associate": "change",
	"Attach": "change", "Enable": "change", "Authorize": "change", "Grant": "change", "Reboot": "change",
	"Restart": "change", "Rotate": "change", "Rename": "change", "Move": "change", "Accept": "change", "Apply": "change",
	"Assign": "change", "Restore": "change", "Resume": "change", "Activate": "change", "Confirm": "change",
	"Delete": "delete", "Remove": "delete", "Terminate": "delete", "Deregister": "delete", "Purge": "delete",
	"Revoke": "delete", "Cancel": "delete", "Detach": "delete", "Disassociate": "delete", "Disable": "delete",
	"Release": "delete", "Stop": "delete", "Reject": "delete", "Untag": "change", "Unsubscribe": "delete",
	"Deactivate": "delete", "Abort": "delete", "Reset": "delete", "Empty": "delete", "Close": "delete",
	"Purchase": "money",
}

var firstWord = regexp.MustCompile(`^[A-Z][a-z]+`)

func kebab(op string) string {
	var b strings.Builder
	rs := []rune(op)
	for i, r := range rs {
		if r >= 'A' && r <= 'Z' {
			if i > 0 && (rs[i-1] >= 'a' && rs[i-1] <= 'z' || (i+1 < len(rs) && rs[i+1] >= 'a' && rs[i+1] <= 'z' && rs[i-1] >= 'A' && rs[i-1] <= 'Z')) {
				b.WriteByte('-')
			}
			b.WriteRune(r + 32)
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}

func main() {
	models := flag.String("models", "", "botocore data folder")
	out := flag.String("out", "adapters/aws-generated.yaml", "output file")
	version := flag.String("version", "", "AWS CLI version the models came from")
	flag.Parse()
	dirs, err := os.ReadDir(*models)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	type svc struct{ ops map[string][]string }
	all := map[string]map[string][]string{}
	total, labelled := 0, 0
	for _, d := range dirs {
		vs, _ := filepath.Glob(filepath.Join(*models, d.Name(), "*", "service-2.json"))
		if len(vs) == 0 {
			continue
		}
		sort.Strings(vs)
		b, err := os.ReadFile(vs[len(vs)-1])
		if err != nil {
			continue
		}
		var m struct {
			Operations map[string]json.RawMessage `json:"operations"`
		}
		if json.Unmarshal(b, &m) != nil {
			continue
		}
		name := d.Name()
		// the CLI calls a few services differently from their model folder
		cliName := map[string]string{"s3": "s3api"}[name]
		if cliName == "" {
			cliName = name
		}
		for op := range m.Operations {
			total++
			w := firstWord.FindString(op)
			act, ok := verbs[w]
			if !ok {
				continue
			}
			labelled++
			if all[cliName] == nil {
				all[cliName] = map[string][]string{}
			}
			all[cliName][act] = append(all[cliName][act], kebab(op))
		}
	}
	var sb strings.Builder
	fmt.Fprintf(&sb, "# Generated by tools/adaptergen from the AWS CLI %s service models.\n", *version)
	fmt.Fprintf(&sb, "# %d of %d operations labelled from their first word; the rest are left to the generic layer (they ask).\n", labelled, total)
	sb.WriteString("# Do not edit by hand: change tools/adaptergen or add a rule to aws.yaml instead.\n")
	sb.WriteString("provider: AWS\ncli: [aws]\ngenerated_operations:\n")
	var names []string
	for n := range all {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		fmt.Fprintf(&sb, "  %s:\n", n)
		var acts []string
		for a := range all[n] {
			acts = append(acts, a)
		}
		sort.Strings(acts)
		for _, a := range acts {
			ops := all[n][a]
			sort.Strings(ops)
			fmt.Fprintf(&sb, "    %s: [%s]\n", a, strings.Join(ops, ", "))
		}
	}
	if err := os.WriteFile(*out, []byte(sb.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("%d services, %d of %d operations labelled -> %s\n", len(names), labelled, total, *out)
}
